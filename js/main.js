function applyLanguage(lang) {
  const dictionary = translations[lang] || translations.bn;
  document.documentElement.lang = lang;
  localStorage.setItem("siteLanguage", lang);
  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dictionary[key]) {
      el.textContent = dictionary[key];
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
}

function initLanguageSwitch() {
  const urlLang = new URLSearchParams(window.location.search).get("lang");
  const savedLanguage = (urlLang === "en" || urlLang === "bn") ? urlLang : (localStorage.getItem("siteLanguage") || "bn");
  applyLanguage(savedLanguage);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      applyLanguage(btn.dataset.lang);
      const url = new URL(window.location.href);
      if (btn.dataset.lang === "en") {
        url.searchParams.set("lang", "en");
      } else {
        url.searchParams.delete("lang");
      }
      window.history.replaceState({}, "", url.toString());
    });
  });
}

function initRevealAnimations() {
  const revealItems = document.querySelectorAll(".reveal");
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  revealItems.forEach((item) => observer.observe(item));
}

function initPageTransitions() {
  document.querySelectorAll("a[href]").forEach((link) => {
    const url = new URL(link.href, window.location.href);
    const isInternalHtml = url.origin === window.location.origin && /\.html?$/.test(url.pathname);
    const isSamePageHash = url.pathname === window.location.pathname && url.hash;

    if (isInternalHtml && !isSamePageHash) {
      link.addEventListener("click", (event) => {
        event.preventDefault();
        document.body.classList.add("is-leaving");
        setTimeout(() => {
          const target = new URL(link.href, window.location.href);
          const currentLang = localStorage.getItem("siteLanguage");
          if (currentLang === "en") target.searchParams.set("lang", "en");
          window.location.href = target.toString();
        }, 260);
      });
    }
  });
}

function initMobileMenu() {
  const toggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector(".main-nav");
  if (!toggle || !nav) return;

  toggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("open");
    toggle.setAttribute("aria-expanded", String(isOpen));
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.getElementById("year").textContent = new Date().getFullYear();
  initLanguageSwitch();
  initRevealAnimations();
  initPageTransitions();
  initMobileMenu();
});


